public class Objsolid{
    int Num_solici;
    String Ubicación;
    String Problema;
    int Tecnico;
    int Prioridad;
    int Estado;
    public Objsolid() {
        
    }

    public String getUbicación() {
        return Ubicación;
    }

    public void setUbicación(String ubicación) {
        Ubicación = ubicación;
    }

    public String getProblema() {
        return Problema;
    }

    public void setProblema(String problema) {
        Problema = problema;
    }

    public int getTecnico() {
        return Tecnico;
    }

    public void setTecnico(int tecnico) {
        Tecnico = tecnico;
    }

    public int getPrioridad() {
        return Prioridad;
    }

    public void setPrioridad(int prioridad) {
        Prioridad = prioridad;
    }

    public int getNum_solici() {
        return Num_solici;
    }

    public void setNum_solici(int num_solici) {
        Num_solici = num_solici;
    }

    public int getEstado() {
        return Estado;
    }

    public void setEstado(int estado) {
        Estado = estado;
    }
}